    function initCustomBooksStorage(callback) {
        // 1. 同步加载 localStorage 镜像，首屏零延迟渲染
        try {
            const raw = localStorage.getItem(STORAGE_KEY_CUSTOM_BOOKS);
            if (raw) {
                const list = JSON.parse(raw);
                if (Array.isArray(list)) {
                    list.forEach(b => {
                        if (b && b.id && b.title && Array.isArray(b.chapters)) {
                            state.books[b.id] = b;
                        }
                    });
                }
            }
        } catch (_) {}

        // 同步加载后立即渲染书架网格与英雄榜，确保首屏刷新即呈现所有本地导入书籍
        renderBookshelfGrid();
        updateBookshelfHero();

        // 2. 异步打开 IndexedDB，支持长篇大体量书籍（大于 2 MiB 镜像阈值）
        try {
            if (window.indexedDB) {
                const req = window.indexedDB.open('lanmao_reader_db_v1', 1);
                req.onupgradeneeded = (e) => {
                    const db = e.target.result;
                    if (!db.objectStoreNames.contains('custom_books')) {
                        db.createObjectStore('custom_books', { keyPath: 'id' });
                    }
                };
                req.onsuccess = (e) => {
                    dbInstance = e.target.result;
                    const tx = dbInstance.transaction('custom_books', 'readonly');
                    const store = tx.objectStore('custom_books');
                    const getAllReq = store.getAll();
                    getAllReq.onsuccess = () => {
                        const books = getAllReq.result || [];
                        let hasNew = false;
                        books.forEach(b => {
                            if (b && b.id && b.title && Array.isArray(b.chapters)) {
                                if (!state.books[b.id] || (b.pdfData && !state.books[b.id].pdfData)) hasNew = true;
                                state.books[b.id] = b;
                            }
                        });
                        state.dbLoaded = true;
                        // 无论是否有新增，只要 IndexedDB 完成读取，均确保网格与英雄榜渲染完整
                        renderBookshelfGrid();
                        updateBookshelfHero();
                        if (typeof callback === 'function') {
                            callback(hasNew);
                        }
                    };
                    getAllReq.onerror = () => {
                        state.dbLoaded = true;
                        if (typeof callback === 'function') callback(false);
                    };
                };
                req.onerror = () => {
                    state.dbLoaded = true;
                    if (typeof callback === 'function') callback(false);
                };
            } else {
                state.dbLoaded = true;
                if (typeof callback === 'function') callback(false);
            }
        } catch (_) {
            state.dbLoaded = true;
            if (typeof callback === 'function') callback(false);
        }
    }

    function saveCustomBook(book, callback) {
        state.books[book.id] = book;

        let mirrorOk = false;
        // 1. 本地存储镜像 (限制体积在 2 MiB 以内，避免超出配额异常)
        try {
            const raw = localStorage.getItem(STORAGE_KEY_CUSTOM_BOOKS);
            let list = raw ? JSON.parse(raw) : [];
            if (!Array.isArray(list)) list = [];
            list = list.filter(b => b.id !== book.id);
            if (book.format === 'pdf') {
                list.push({
                    id: book.id,
                    title: book.title,
                    author: book.author,
                    coverEmoji: book.coverEmoji,
                    format: 'pdf',
                    chapters: book.chapters
                });
            } else {
                list.push(book);
            }
            const serialized = JSON.stringify(list);
            if (serialized.length < 2 * 1024 * 1024) {
                localStorage.setItem(STORAGE_KEY_CUSTOM_BOOKS, serialized);
                mirrorOk = true;
            }
        } catch (err) {
            console.warn('localStorage custom books mirror failed:', err);
        }

        // 2. 写入 IndexedDB (大文件持久化主通道，严格遵循事务生命周期与单次回调保护)
        let called = false;
        const done = (ok) => {
            if (!called) {
                called = true;
                if (typeof callback === 'function') callback(ok);
            }
        };

        const executePut = (db) => {
            try {
                const tx = db.transaction('custom_books', 'readwrite');
                const store = tx.objectStore('custom_books');
                const req = store.put(book);
                req.onerror = (e) => {
                    console.warn('IndexedDB put error:', req.error || e);
                };
                tx.oncomplete = () => {
                    done(true);
                };
                tx.onabort = () => {
                    console.warn('IndexedDB transaction aborted');
                    done(mirrorOk);
                };
                tx.onerror = () => {
                    console.warn('IndexedDB transaction error:', tx.error);
                    done(mirrorOk);
                };
            } catch (err) {
                console.warn('IndexedDB transaction failed:', err);
                done(mirrorOk);
            }
        };

        if (dbInstance) {
            executePut(dbInstance);
        } else if (window.indexedDB) {
            try {
                const openReq = window.indexedDB.open('lanmao_reader_db_v1', 1);
                openReq.onupgradeneeded = (e) => {
                    const db = e.target.result;
                    if (!db.objectStoreNames.contains('custom_books')) {
                        db.createObjectStore('custom_books', { keyPath: 'id' });
                    }
                };
                openReq.onsuccess = (e) => {
                    dbInstance = e.target.result;
                    executePut(dbInstance);
                };
                openReq.onerror = () => {
                    done(mirrorOk);
                };
            } catch (_) {
                done(mirrorOk);
            }
        } else {
            done(mirrorOk);
        }
    }

    function deleteCustomBook(bookId) {
        delete state.books[bookId];

        // 1. 从 localStorage 镜像移除
        try {
            const raw = localStorage.getItem(STORAGE_KEY_CUSTOM_BOOKS);
            if (raw) {
                let list = JSON.parse(raw);
                if (Array.isArray(list)) {
                    list = list.filter(b => b.id !== bookId);
                    localStorage.setItem(STORAGE_KEY_CUSTOM_BOOKS, JSON.stringify(list));
                }
            }
        } catch (_) {}

        // 2. 从 IndexedDB 移除
        try {
            if (dbInstance) {
                const tx = dbInstance.transaction('custom_books', 'readwrite');
                tx.objectStore('custom_books').delete(bookId);
            }
        } catch (_) {}

        // 3. 从进度记录中移除
        try {
            const rawProg = localStorage.getItem(STORAGE_KEY_BOOK_PROGRESS);
            if (rawProg) {
                const map = JSON.parse(rawProg);
                delete map[bookId];
                localStorage.setItem(STORAGE_KEY_BOOK_PROGRESS, JSON.stringify(map));
            }
        } catch (_) {}

        const saved = loadSavedProgress();
        if (saved && saved.bookId === bookId) {
            localStorage.removeItem(STORAGE_KEY_PROGRESS);
        }

        // 4. 若删除的书恰好是当前活跃书籍，重置为默认书《小王子》并清理路由参数
        if (state.currentBookId === bookId) {
            state.currentBookId = 'prince';
            state.currentBook = state.books.prince || BUILTIN_BOOKS.prince;
            state.currentChapterIndex = 0;
            state.currentPage = 1;

            try {
                const url = new URL(window.location.href);
                if (url.searchParams.get('book') === bookId) {
                    url.searchParams.delete('book');
                    url.searchParams.delete('chapter');
                    url.searchParams.delete('page');
                    window.history.replaceState({ view: 'bookshelf' }, '', url.toString());
                }
            } catch (_) {}

            if (state.activeView === 'reader') {
                switchView('bookshelf', null, null, null, false);
            }
        }

        renderBookshelfGrid();
        updateBookshelfHero();
        showToast('已从本机移除该书');
    }

