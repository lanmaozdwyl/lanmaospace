    function switchView(viewName, bookId, chapterIndex, page, pushHistory = true) {
        const shelfView = document.getElementById('view-bookshelf');
        const readerView = document.getElementById('view-reader');
        if (!shelfView || !readerView) return;

        if (viewName === 'reader') {
            shelfView.hidden = true;
            readerView.hidden = false;
            state.activeView = 'reader';

            const targetBookId = bookId || state.currentBookId || 'prince';
            const targetChapter = typeof chapterIndex === 'number' ? chapterIndex : (state.currentChapterIndex || 0);
            const targetPage = typeof page === 'number' ? page : (state.currentPage || 1);

            loadBook(targetBookId, targetChapter, targetPage);
            hideMenu();

            try {
                const url = new URL(window.location.href);
                url.searchParams.set('book', targetBookId);
                const historyState = { view: 'reader', bookId: targetBookId };
                if (pushHistory) {
                    window.history.pushState(historyState, '', url.toString());
                } else {
                    window.history.replaceState(historyState, '', url.toString());
                }
            } catch (_) {}
        } else {
            destroyOpenPageFlip();
            destroyPdfBook();
            readerView.hidden = true;
            shelfView.hidden = false;
            state.activeView = 'bookshelf';

            closeAllDrawers();
            updateBookshelfHero();

            try {
                const url = new URL(window.location.href);
                url.searchParams.delete('book');
                const historyState = { view: 'bookshelf' };
                if (pushHistory) {
                    window.history.pushState(historyState, '', url.toString());
                } else {
                    window.history.replaceState(historyState, '', url.toString());
                }
            } catch (_) {}
        }

        // 同步侧边微动翻页条显示状态
        const edgeRocker = document.getElementById('reader-edge-rocker');
        if (edgeRocker) {
            edgeRocker.classList.toggle('hidden', !state.settings.edgeRockerEnabled || state.activeView !== 'reader');
        }
    }

