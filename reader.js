    function handleLocalFileInput(file) {
        if (!file) {
            resetFileInputs();
            return;
        }
        const cleanName = file.name ? file.name.replace(/\.[^/.]+$/, '').trim() : '本地书籍';
        setImportingState(true, `正在载入《${cleanName}》，请稍候…`);
        showToast(`正在载入《${cleanName}》，请稍候…`, 2500);

        const finishImport = () => {
            setImportingState(false);
            resetFileInputs();
        };

        const reader = new FileReader();
        reader.onload = function (e) {
            const buffer = e.target.result;
            if (!buffer || buffer.byteLength === 0) {
                finishImport();
                showToast('文件内容为空，请重新选择');
                return;
            }

            // 0. PDF 格式检测与 3D 翻页入库
            const uint8 = new Uint8Array(buffer.slice(0, 4));
            const isPdfExt = file.name.toLowerCase().endsWith('.pdf');
            const isPdfType = file.type === 'application/pdf';
            const isPdfMagic = (uint8[0] === 0x25 && uint8[1] === 0x50 && uint8[2] === 0x44 && uint8[3] === 0x46); // %PDF
            if (isPdfExt || isPdfType || isPdfMagic) {
                const bookObj = {
                    id: 'custom_pdf_' + Date.now() + '_' + Math.random().toString(36).slice(2, 7),
                    title: cleanName || '本地 PDF 文档',
                    author: '本地导入 PDF',
                    coverEmoji: '📑',
                    format: 'pdf',
                    pdfData: buffer,
                    chapters: [{ title: cleanName || '本地 PDF 文档', page: 1 }],
                    totalPages: 1
                };
                saveCustomBook(bookObj, (success) => {
                    if (success) {
                        showToast(`📖 已载入 PDF《${bookObj.title}》，已保存在本机书架！`, 3200);
                    } else {
                        showToast(`⚠️ 《${bookObj.title}》已载入临时阅读，但本机存储已满，刷新可能不会保留`, 4000);
                    }
                });
                renderBookshelfGrid();
                switchView('reader', bookObj.id, 0, 1);
                closeAllDrawers();
                finishImport();
                return;
            }

            // 1. 严格检查二进制头与文件类型（拒绝未解压的 EPUB / ZIP 二进制压缩包）
            const isZipMagic = uint8[0] === 0x50 && uint8[1] === 0x4B && uint8[2] === 0x03 && uint8[3] === 0x04;
            const isEpubExt = file.name.toLowerCase().endsWith('.epub');

            if (isZipMagic || isEpubExt) {
                finishImport();
                showToast('⚠️ 暂不支持 EPUB 压缩格式，请导入 TXT 或 Markdown (.md) 纯文本书籍', 4000);
                return;
            }

            let text = '';
            try {
                // 优先使用严格 UTF-8 解码，遇到非法序列抛错
                const utf8 = new TextDecoder('utf-8', { fatal: true });
                text = utf8.decode(buffer);
            } catch (_) {
                // 兼容中文电子书广泛使用的 GBK / GB2312 / GB18030 编码格式
                try {
                    const gbk = new TextDecoder('gb18030');
                    text = gbk.decode(buffer);
                } catch (err) {
                    const fallback = new TextDecoder('utf-8');
                    text = fallback.decode(buffer);
                }
            }
            if (!text || !text.trim()) {
                finishImport();
                showToast('文件解析为空，请重新选择');
                return;
            }
            const bookObj = parseUploadedFile(file.name, text);
            saveCustomBook(bookObj, (success) => {
                if (success) {
                    showToast(`📖 已载入《${bookObj.title}》，已保存在本机书架！`, 3200);
                } else {
                    showToast(`⚠️ 《${bookObj.title}》已载入临时阅读，但本机存储已满，刷新可能不会保留`, 4000);
                }
            });
            renderBookshelfGrid();
            switchView('reader', bookObj.id, 0, 1);
            closeAllDrawers();
            finishImport();
        };
        reader.onerror = function () {
            finishImport();
            showToast('读取文件失败，请检查文件格式');
        };
        reader.readAsArrayBuffer(file);
    }

